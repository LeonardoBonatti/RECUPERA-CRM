// Cria o schema (idempotente), as regionais iniciais e os acessos de bootstrap-users.js.
// Roda automaticamente no primeiro acesso de cada instância e também via `npm run db:setup`.
import { transaction } from './db.js';
import { hashPassword, generatePassword } from './auth.js';
import { BOOTSTRAP_USERS, INITIAL_PASSWORD } from './bootstrap-users.js';
import { normKey, opportunityKey } from './normalize.js';

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS regions (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    text NOT NULL UNIQUE,
    active  boolean NOT NULL DEFAULT true
  );

  -- Filial → Regional. Tem prioridade sobre a coluna Regional da planilha.
  CREATE TABLE IF NOT EXISTS branches (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    name_key   text NOT NULL UNIQUE,
    region_id  integer NOT NULL REFERENCES regions(id)
  );

  CREATE TABLE IF NOT EXISTS users (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  text NOT NULL,
    email                 text NOT NULL UNIQUE,          -- sempre gravado em minúsculas
    password_hash         text NOT NULL,
    role                  text NOT NULL CHECK (role IN ('NACIONAL','REGIONAL','EXECUTIVO','VISUALIZADOR')),
    region_id             integer REFERENCES regions(id),
    active                boolean NOT NULL DEFAULT true,
    must_change_password  boolean NOT NULL DEFAULT true,
    created_at            timestamptz NOT NULL DEFAULT now()
  );

  -- Regionais de um Gerente Regional (pode cuidar de mais de uma, ex.: Norte e Nordeste).
  -- users.region_id guarda a primeira; executivos usam só users.region_id.
  CREATE TABLE IF NOT EXISTS user_regions (
    user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    region_id  integer NOT NULL REFERENCES regions(id),
    PRIMARY KEY (user_id, region_id)
  );

  CREATE TABLE IF NOT EXISTS sessions (
    token_hash  text PRIMARY KEY,
    user_id     integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at  timestamptz NOT NULL
  );

  -- Marcadores de tarefas executadas uma única vez.
  CREATE TABLE IF NOT EXISTS app_settings (
    key    text PRIMARY KEY,
    value  text
  );

  -- Bloqueio de força bruta no login (precisa ficar no banco: serverless não tem memória compartilhada).
  CREATE TABLE IF NOT EXISTS login_attempts (
    key           text PRIMARY KEY,
    failures      integer NOT NULL DEFAULT 0,
    locked_until  timestamptz
  );

  -- Cada upload do Gerente Nacional é uma "base" (ex.: Agosto/26).
  CREATE TABLE IF NOT EXISTS imports (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label        text NOT NULL,
    file_name    text,
    uploaded_by  integer REFERENCES users(id),
    total_rows   integer NOT NULL DEFAULT 0,
    created_at   timestamptz NOT NULL DEFAULT now()
  );

  CREATE TABLE IF NOT EXISTS leads (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id          integer NOT NULL REFERENCES imports(id) ON DELETE CASCADE,
    row_number         integer,
    client_name        text NOT NULL,
    client_doc         text,
    client_key         text NOT NULL,
    region_label       text,
    branch             text,
    region_id          integer REFERENCES regions(id),
    machine            text,
    quantity           numeric(12,2) NOT NULL DEFAULT 1,
    amount             numeric(18,2) NOT NULL DEFAULT 0,
    loss_reason        text,
    origin_manager     text,
    origin_seller      text,
    contact_name       text,
    phone              text,
    email              text,
    city               text,
    state              text,
    opportunity_date   text,
    raw_data           jsonb NOT NULL,        -- linha original completa: nada da planilha se perde
    legacy_values      jsonb,                 -- respostas antigas fora das listas fechadas
    in_previous_base   boolean NOT NULL DEFAULT false,
    executive_id       integer REFERENCES users(id),
    assigned_at        timestamptz,
    first_base         text,
    origin_return      text,
    bought_competitor  text,
    contact_status     text,
    contact_summary    text,
    completed_at       timestamptz,
    updated_at         timestamptz,
    updated_by         integer REFERENCES users(id)
  );
  CREATE INDEX IF NOT EXISTS ix_leads_region    ON leads(region_id);
  CREATE INDEX IF NOT EXISTS ix_leads_executive ON leads(executive_id);
  CREATE INDEX IF NOT EXISTS ix_leads_import    ON leads(import_id);
  CREATE INDEX IF NOT EXISTS ix_leads_client    ON leads(client_key);

  -- Trilha de auditoria: roteamento, atribuição e cada campo alterado.
  CREATE TABLE IF NOT EXISTS lead_history (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id     integer NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
    user_id     integer REFERENCES users(id),
    action      text NOT NULL,
    field       text,
    old_value   text,
    new_value   text,
    created_at  timestamptz NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS ix_history_lead ON lead_history(lead_id);

  -- Evoluções do schema (idempotentes, para bancos já criados).
  ALTER TABLE users ADD COLUMN IF NOT EXISTS aliases text[] NOT NULL DEFAULT '{}';
  -- Gerente da parceira responsável pelo lead (coluna de gerente da planilha ou quem atribuiu).
  ALTER TABLE leads ADD COLUMN IF NOT EXISTS manager_id integer REFERENCES users(id);
  -- Nomes como vieram na planilha, para conferência.
  ALTER TABLE leads ADD COLUMN IF NOT EXISTS partner_manager_label text;
  ALTER TABLE leads ADD COLUMN IF NOT EXISTS partner_executive_label text;
  CREATE INDEX IF NOT EXISTS ix_leads_manager ON leads(manager_id);
  -- Impressão digital da oportunidade (detecção de duplicidade na importação).
  ALTER TABLE leads ADD COLUMN IF NOT EXISTS dedup_key text;
  CREATE INDEX IF NOT EXISTS ix_leads_dedup ON leads(dedup_key);
  -- Atuação da equipe: último acesso e consultas de histórico por pessoa/data.
  ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login_at timestamptz;
  CREATE INDEX IF NOT EXISTS ix_history_user ON lead_history(user_id, created_at);
`;

let ready = null;

export function ensureReady() {
  ready ??= init().catch(err => { ready = null; throw err; });
  return ready;
}

async function init() {
  await transaction(async tx => {
    // Evita que duas instâncias criem o schema/usuários ao mesmo tempo.
    await tx.run('SELECT pg_advisory_xact_lock(727274)');
    await tx.exec(SCHEMA);

    if ((await tx.get('SELECT count(*) AS n FROM regions')).n === 0) {
      const regions = (process.env.SEED_REGIONS || 'Centro-Oeste,Leste,Nordeste,Norte,Sudeste')
        .split(',').map(s => s.trim()).filter(Boolean);
      for (const name of regions) await tx.run('INSERT INTO regions (name) VALUES (?) ON CONFLICT (name) DO NOTHING', name);
    }

    await ensureBootstrapUsers(tx);
    await applyInitialPasswordOnce(tx);
    await backfillDedupKeys(tx);
  });
}

// Leads importados antes da detecção de duplicidade ganham a impressão digital.
async function backfillDedupKeys(tx) {
  const missing = await tx.all(
    'SELECT id, client_name, client_doc, machine, quantity, amount, branch FROM leads WHERE dedup_key IS NULL');
  if (!missing.length) return;
  const rows = missing.map(l => ({ id: l.id, key: opportunityKey(l) }));
  await tx.run(`
    UPDATE leads l SET dedup_key = x.key
    FROM jsonb_to_recordset(?::jsonb) AS x(id int, key text) WHERE l.id = x.id`, JSON.stringify(rows));
  console.log(`[duplicidade] impressão digital calculada para ${rows.length} lead(s) existentes.`);
}

// Uma única vez: quem ainda não fez o 1º acesso (inclusive usuários criados antes, com senha
// aleatória) passa a entrar com a senha inicial comum. Depois disso, nunca mais mexe em senhas.
async function applyInitialPasswordOnce(tx) {
  const MARKER = 'initial_password_v1';
  // Sem senha inicial configurada não há o que aplicar (e nunca mexe em senhas existentes).
  if (!INITIAL_PASSWORD) return;
  if (await tx.get('SELECT 1 FROM app_settings WHERE key = ?', MARKER)) return;
  const pending = await tx.all('SELECT id FROM users WHERE must_change_password AND active');
  for (const { id } of pending) {
    await tx.run('UPDATE users SET password_hash = ? WHERE id = ?', hashPassword(INITIAL_PASSWORD), id);
  }
  await tx.run('INSERT INTO app_settings (key, value) VALUES (?, now()::text)', MARKER);
  console.log(`[acessos] senha inicial aplicada a ${pending.length} usuário(s) que ainda não tinham acessado.`);
}

// Cria os acessos de bootstrap-users.js (e ADMIN_EMAIL, se definido) que ainda não existem.
async function ensureBootstrapUsers(tx) {
  const wanted = [...BOOTSTRAP_USERS];
  if (process.env.ADMIN_EMAIL) {
    wanted.push({ name: 'Gerente Nacional', email: process.env.ADMIN_EMAIL, role: 'NACIONAL' });
  }
  const regionByKey = new Map((await tx.all('SELECT id, name FROM regions')).map(r => [normKey(r.name), r.id]));

  for (const u of wanted) {
    const email = u.email.trim().toLowerCase();
    const aliases = Array.isArray(u.aliases) ? u.aliases.map(String) : [];
    // Usuário que já existe é gerenciado pela tela; a lista nunca altera nada dele
    // (inclusive os apelidos, que agora são editados em "Equipe e acessos").
    if (await tx.get('SELECT id FROM users WHERE email = ?', email)) continue;

    const regionNames = u.role === 'REGIONAL' ? (u.regions || []) : u.role === 'EXECUTIVO' ? [u.region] : [];
    const regionIds = regionNames.map(name => regionByKey.get(normKey(name)));
    if (regionIds.some(id => !id) || (['REGIONAL', 'EXECUTIVO'].includes(u.role) && !regionIds.length)) {
      console.warn(`[acessos] ${email}: regional "${regionNames.join(', ')}" não encontrada; usuário não criado.`);
      continue;
    }

    // Senha inicial configurada (ADMIN_PASSWORD) ou aleatória; troca obrigatória no 1º login.
    const { id } = await tx.get(
      'INSERT INTO users (name, email, password_hash, role, region_id, aliases) VALUES (?, ?, ?, ?, ?, ?::text[]) RETURNING id',
      u.name || email, email, hashPassword(INITIAL_PASSWORD || generatePassword()), u.role, regionIds[0] ?? null, aliases);
    if (u.role === 'REGIONAL') {
      for (const regionId of regionIds) await tx.run('INSERT INTO user_regions (user_id, region_id) VALUES (?, ?)', id, regionId);
    }
    console.log(`[acessos] criado ${u.role} ${email}${INITIAL_PASSWORD ? '' : ' (senha aleatória: use "Gerar acesso" na tela)'}`);
  }
}
